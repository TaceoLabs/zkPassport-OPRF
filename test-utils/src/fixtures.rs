//! Test fixture loading for zkPassport OPRF tests.
//!
//! Reads proofs, `privateNullifier`, and `beta` from the bundled
//! `fixtures/zkpassport-proofs.json` file and the v2 request bodies from `fixtures/oprf-v2/`.

use ark_ff::PrimeField;
use serde::{Deserialize, Deserializer, de::Error as _};
use zkpassport_oprf_authentication::{AuthCommitment, SaltedIdentifier, ZKPassportProofResult};

/// Fixture data loaded from `fixtures/zkpassport-proofs.json`.
pub struct FixtureData {
    pub proofs: Vec<ZKPassportProofResult>,
    pub private_nullifier: ark_babyjubjub::Fq,
    pub beta: ark_babyjubjub::Fr,
}

fn hex_to_bytes(hex: &str) -> Vec<u8> {
    let hex = hex.strip_prefix("0x").unwrap_or(hex);
    let hex = if !hex.len().is_multiple_of(2) {
        format!("0{hex}")
    } else {
        hex.to_string()
    };
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("Invalid hex"))
        .collect()
}

/// Load the fixtures file as raw JSON, as produced by zkPassport.
///
/// Besides the fields read by [`load_fixture_data`], it contains the
/// `blinded_unique_identifier` computed by zkPassport from `privateNullifier` and `beta`.
pub fn load_fixture_json() -> serde_json::Value {
    let fixture_path = concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/fixtures/zkpassport-proofs.json"
    );
    let data = std::fs::read_to_string(fixture_path)
        .unwrap_or_else(|e| panic!("Failed to read fixture file {fixture_path}: {e}"));
    serde_json::from_str(&data).expect("Failed to parse fixture JSON")
}

/// Load ZKPassport proofs, privateNullifier, and beta from the fixtures file.
pub fn load_fixture_data() -> FixtureData {
    let value = load_fixture_json();

    let proofs: Vec<ZKPassportProofResult> =
        serde_json::from_value(value["proofs"].clone()).expect("Failed to parse proofs");

    let pn_hex = value["privateNullifier"]
        .as_str()
        .expect("Missing privateNullifier");
    let private_nullifier = ark_babyjubjub::Fq::from_be_bytes_mod_order(&hex_to_bytes(pn_hex));

    let beta_hex = value["beta"].as_str().expect("Missing beta");
    let beta = ark_babyjubjub::Fr::from_be_bytes_mod_order(&hex_to_bytes(beta_hex));

    FixtureData {
        proofs,
        private_nullifier,
        beta,
    }
}

/// Request body of the verifier's `oprf/v2/identify` route and the identify OPRF request.
#[derive(Debug, Clone, Deserialize)]
pub struct IdentifyFixture {
    pub proofs: Vec<ZKPassportProofResult>,
    #[serde(deserialize_with = "deserialize_hex_point")]
    pub blinded_query: ark_babyjubjub::EdwardsAffine,
}

/// Request body of the verifier's `oprf/v2/register` and `oprf/v2/rotate` routes.
///
/// For rotation, `commitment` is the new commitment.
#[derive(Debug, Clone, Deserialize)]
pub struct CommitmentFixture {
    pub proofs: Vec<ZKPassportProofResult>,
    #[serde(rename = "I")]
    pub salted_identifier: SaltedIdentifier,
    pub commitment: AuthCommitment,
}

/// Request body of the verifier's `oprf/v2/query` route and the nullifier OPRF request.
#[derive(Debug, Clone, Deserialize)]
pub struct QueryFixture {
    pub proofs: Vec<ZKPassportProofResult>,
    #[serde(deserialize_with = "deserialize_hex_point")]
    pub blinded_query: ark_babyjubjub::EdwardsAffine,
    #[serde(rename = "I")]
    pub salted_identifier: SaltedIdentifier,
    /// The commitment stored for `I`, as registered by [`V2Fixtures::register`].
    pub commitment: AuthCommitment,
}

/// The v2 request bodies for one passport, generated by zkPassport.
///
/// They only verify in the verifier's `devmode` and in the order identify, register, query,
/// rotate. After the rotation, `query` no longer verifies.
#[derive(Debug, Clone)]
pub struct V2Fixtures {
    pub identify: IdentifyFixture,
    pub register: CommitmentFixture,
    pub query: QueryFixture,
    pub rotate: CommitmentFixture,
}

/// Load the v2 fixtures from `fixtures/oprf-v2/`.
pub fn load_v2_fixtures() -> V2Fixtures {
    V2Fixtures {
        identify: load_v2_fixture("identify"),
        register: load_v2_fixture("register"),
        query: load_v2_fixture("query"),
        rotate: load_v2_fixture("rotate"),
    }
}

fn load_v2_fixture<T: serde::de::DeserializeOwned>(name: &str) -> T {
    let path = format!(
        "{}/fixtures/oprf-v2/{name}.json",
        env!("CARGO_MANIFEST_DIR")
    );
    let data = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("Failed to read fixture file {path}: {e}"));
    serde_json::from_str(&data).unwrap_or_else(|e| panic!("Failed to parse {path}: {e}"))
}

/// Parses `0x` followed by the big-endian hex of the x and y coordinate, 32 bytes each.
fn deserialize_hex_point<'de, D: Deserializer<'de>>(
    deserializer: D,
) -> Result<ark_babyjubjub::EdwardsAffine, D::Error> {
    let hex = String::deserialize(deserializer)?;
    let bytes: [u8; 64] = hex_to_bytes(&hex)
        .try_into()
        .map_err(|_| D::Error::custom("expected 64 bytes"))?;
    let (x, y) = bytes.split_at(32);
    let point = ark_babyjubjub::EdwardsAffine::new_unchecked(
        ark_babyjubjub::Fq::from_be_bytes_mod_order(x),
        ark_babyjubjub::Fq::from_be_bytes_mod_order(y),
    );
    if point.is_on_curve() && point.is_in_correct_subgroup_assuming_on_curve() {
        Ok(point)
    } else {
        Err(D::Error::custom("point is not in the prime-order subgroup"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn v2_fixtures_belong_to_one_passport() {
        let fixtures = load_v2_fixtures();
        assert_eq!(
            fixtures.identify.blinded_query,
            fixtures.query.blinded_query
        );
        assert_eq!(
            fixtures.register.salted_identifier,
            fixtures.query.salted_identifier
        );
        assert_eq!(fixtures.register.commitment, fixtures.query.commitment);
        assert_eq!(
            fixtures.register.salted_identifier,
            fixtures.rotate.salted_identifier
        );
        assert_ne!(fixtures.register.commitment, fixtures.rotate.commitment);
    }
}
